/** よくある質問 1 件。 */
export interface FaqItem {
  q: string
  a: string
}

/**
 * よくある質問。対応している試験の質問は、テンプレートの試験名から作る
 * （試験名が無いときは、どの試験にも使えることだけを答える）。
 */
export function faqItems(examNames: string[]): FaqItem[] {
  const exams =
    examNames.length > 0
      ? `どの資格試験にも使えます。${examNames.join('・')}は、出題分野のカテゴリがそろったテンプレートから始められます。`
      : 'どの資格試験にも使えます。試験名を入力して作り、カテゴリ（分野）を自由に登録できます。'
  return [
    { q: 'どの資格試験に使えますか？', a: exams },
    {
      q: '問題集の本文を入力する必要はありますか？',
      a: 'ありません。問題集の名称と問題番号、回答だけを記録します。お手持ちの問題集・過去問・模試にそのまま使えます。',
    },
    {
      q: '復習のタイミングはどうやって決まりますか？',
      a: '問題ごとに、最新から数えて連続で正解した回数（習熟度）を求め、1・3・7・14・30・60 日後に復習日を設定します。間違えると翌日に戻ります。',
    },
    {
      q: 'スマートフォンでも使えますか？',
      a: '使えます。ブラウザのメニューから「ホーム画面に追加」すると、アプリのように起動できます。',
    },
    {
      q: '一覧に無い試験でも使えますか？',
      a: '使えます。試験名を入力して作り、カテゴリ（分野）を自由に登録できます。',
    },
    {
      q: '記録したデータを持ち出せますか？',
      a: '試験ごとに、採点済みの回答を CSV（Excel で開ける形式）で書き出せます。',
    },
  ]
}
